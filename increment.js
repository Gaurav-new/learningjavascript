let count = 5;
console.log(count);
let count1 = ++count; //(increments value of count by 1)
console.log(count1);
let count2 = count++; //increments value of count by 1)
console.log(count); //7
console.log(count1); //6
console.log(count2); //6


/* ++count (Pre-increment): The value is incremented before it is used in the expression.
count++ (Post-increment): The value is incremented after its current value is used in the expression. 
*/

